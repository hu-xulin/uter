import { notFound } from 'next/navigation';
import fs from 'node:fs';
import path from 'node:path';

import { MarkdownBody } from '@/lib/content-renderer';
import { loadMarkdownPage, loadSectionNav } from '@/lib/content/markdown-page';
import { DocsShell } from '@/lib/docs-shell';
import { SUPPORTED_DOCS_LOCALES, docsLocaleFromSegment } from '@/lib/i18n';

/**
 * One group of API endpoints, at `/docs/<lang>/api/<group>/`.
 *
 * Upstream publishes a page per endpoint. Reproducing that verbatim
 * would put two hundred entries in the sidebar, where a flat list stops
 * being navigation. Endpoints are grouped by their upstream directory
 * instead — the same grouping upstream's own sidebar uses — and each one
 * is an `h2` here, so it keeps both a deep link and a TOC entry.
 */
const CONTENT_ROOT = path.join(process.cwd(), 'content');

/**
 * Group slugs present as `content/api/<locale>/*.md`, excluding the index.
 *
 * Pages are statically generated from these on disk rather than from
 * `_nav.json` alone: `_nav.json` is regenerated by the upstream sync and
 * a hand-authored group (such as `ai-model-audio-gemini`, the native
 * Gemini audio format) would otherwise vanish from the build whenever the
 * sync re-runs. `loadSectionNav` is merged in so any group listed there
 * but without a matching file is still attempted (and `notFound()`-ed if
 * absent).
 */
function apiGroupsForLocale(locale: string): string[] {
  const dir = path.join(CONTENT_ROOT, 'api', locale);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((file) => file.endsWith('.md') && file !== 'index.md')
    .map((file) => file.slice(0, -3));
}

export function generateStaticParams() {
  return SUPPORTED_DOCS_LOCALES.flatMap((lang) =>
    [...new Set([...apiGroupsForLocale(lang), ...loadSectionNav('api', lang).map((item) => item.id)])].map(
      (group) => ({ lang, group })
    )
  );
}

export default async function ApiGroupPage(props: {
  params: Promise<{ lang: string; group: string }>;
}) {
  const { lang, group } = await props.params;
  const locale = docsLocaleFromSegment(lang);
  const page = loadMarkdownPage(`api/${locale}/${group}.md`);
  if (!page) notFound();

  return (
    <DocsShell locale={locale} title={page.title} toc={page.toc}>
      <MarkdownBody html={page.html} />
    </DocsShell>
  );
}
