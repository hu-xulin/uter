// Atomic cross-process lock. `mkdirSync` is atomic on every supported platform,
// unlike an exclusive-create file + read/modify/write cycle. Without this lock
// two parallel `node --test` workers both observe a stale identity and each
// open a NEW execution in the same millisecond, so evidence produced during a
// single verification run ends up bound to different execution_ids.
const LOCK = path.join(STATE, '.execution-identity.lock');
const LOCK_STALE_MS = 30_000;
// `node --test` runs every UAP test file in its own process and the identity
// race test itself spawns 8+4 workers, so 20+ processes may contend for this
// lock at once. A 5s deadline timed out under that real load even though the
// lock was healthy (see UAP-FINAL-REMEDIATION-BASELINE.json). Wait at least as
// long as a stale holder can be reclaimed, plus headroom. This widens the
// WAIT, not the assertion: a genuinely stuck lock still fails closed.
const LOCK_WAIT_MS = Number(process.env.UAP_IDENTITY_LOCK_WAIT_MS || (LOCK_STALE_MS + 15_000));

