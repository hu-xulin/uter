// Pathspec exclusions keep runtime-only artefacts out of the diff hashes. A
// report written during a verification run must NOT invalidate evidence
// produced earlier in the SAME run. Business-code content MUST.
const DIFF_EXCLUDES = Object.freeze([
  ':(exclude).uap/state', ':(exclude).uap/reports', ':(exclude).uap/evidence',
  `:(exclude)${GENERATED_INDEX}`,
  ':(exclude)tsgo-cache',
  ...GENERATED_AUDIT_REPORTS.map((f) => `:(exclude)${f}`),
  ...GENERATED_FRONTEND_BUILD.map((f) => `:(exclude)${f}`),
  ...GENERATED_UDS_OUTPUTS.map((f) => `:(exclude)${f}`),
]);

function isVolatile(file) {
  return VOLATILE_PREFIXES.some((p) => file === p || file.startsWith(p));
}

function git(args, { trim = true } = {}) {
  try {
    const output = execFileSync('git', args, {
      cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'],
      timeout: 15000,
      // Binary diffs (e.g. regenerated PNG visual baselines) can exceed the
      // default 1 MiB execFileSync buffer and throw ENOBUFS, which would be
      // swallowed into a fail-closed `null` and break worktreeFingerprint().
      maxBuffer: 64 * 1024 * 1024,
    });
    // `git status --porcelain` encodes the status in the first two columns of
    // EVERY line. Trimming the whole output strips the leading space of the
    // FIRST line and corrupts its 3-column prefix, so worktreeFingerprint()
    // must request the raw output.
    return trim ? output.trim() : output;
  } catch (error) {
    // fail-closed: never fabricate a HEAD or a clean worktree
    return null;
  }
}

/** Real current HEAD. Null when git cannot be queried. */
export function gitHead() {
  const head = git(['rev-parse', 'HEAD']);
  return head && /^[0-9a-f]{40}$/.test(head) ? head : null;
}

/**
 * Content-bearing fingerprint of the ACTUAL worktree.
 *
 * Phase-2 audit defect: the old implementation hashed only `git status` status
 * LINES (XY code + path) with `--untracked-files=no`. Consequences:
 *   - a clean tree hashed the empty string -> every report carried
 *     `e3b0c442...` (SHA256 of ""), which proves nothing;
 *   - editing a file's CONTENT without changing the set of modified files left
 *     the fingerprint unchanged, so reports stayed "valid" for different code;
 *   - newly created (untracked) business files were invisible.
 *
 * The new fingerprint binds: HEAD, the exact status lines, the full unstaged
 * diff, the full staged diff, and the CONTENT of every non-volatile untracked
 * file. Runtime artefacts under .uap/{state,reports,evidence} are excluded so
 * writing evidence does not invalidate its own run; everything else counts.
 *
 * It is independently recomputable:
 *   git -C <root> status --porcelain=v1 --untracked-files=all
 *   git -C <root> diff --binary -- . ':(exclude).uap/state' ... etc.
 *   sha256 of each non-volatile untracked file (base64 of raw bytes)
 */
export function worktreeFingerprint() {
  const head = gitHead();
  const out = git(['status', '--porcelain=v1', '--untracked-files=all'], { trim: false });
  if (out === null || head === null) return null;
  const lines = out.split('\n').map((l) => l.trimEnd()).filter(Boolean)
    .filter((line) => !isVolatile(line.slice(3).split(' -> ').pop()))
    .sort();

  const unstaged = git(['diff', '--binary', '--', '.', ...DIFF_EXCLUDES], { trim: false });
  const staged = git(['diff', '--cached', '--binary', '--', '.', ...DIFF_EXCLUDES], { trim: false });
  if (unstaged === null || staged === null) return null; // fail-closed

  const parts = [
    `head:${head}`,
    `unstaged:${hash(unstaged)}`,
    `staged:${hash(staged)}`,
  ];
  for (const line of lines) {
    const file = line.slice(3).split(' -> ').pop();
    parts.push(`status:${line}`);
    // `??` entries are untracked files; bind their CONTENT, not just the name.
    if (line.startsWith('??')) {
      const abs = path.join(ROOT, file);
      try {
        if (fs.statSync(abs).isFile()) {
          parts.push(`untracked:${file}:${hash(fs.readFileSync(abs).toString('base64'))}`);
        }
      } catch { /* vanished concurrently: fail closed below */ }
    }
  }
  return hash(parts.sort().join('\n'));
}

/** Explain the fingerprint (used by the evidence manifest / final gate). */
export function fingerprintBasis() {
  return {
    algorithm: 'sha256(sorted( head + status-lines + sha256(git diff --binary) + sha256(git diff --cached --binary) + sha256(untracked file bytes base64) ))',
    excludes: [...VOLATILE_PREFIXES],
    includes_untracked_files: true,
    includes_file_content: true,
    note: 'runtime artefacts (.uap/state, .uap/reports, .uap/evidence), the generated SPECIFICATION-INDEX.md, the tsgo-cache build cache, the generated frontend build outputs (web/public/docs-search, sitemap.xml), the generated design-system audit/*.json reports and the UDS 8.0.0 code-generation outputs (runtime/, registries, specification docs, SHOWCASE, public copies, semantic bridge, chart palette, visual-regression/uds8 run logs+screenshots) are excluded; all SOURCE remains bound (registry/*.mjs, component-registry.json, the frozen VISUAL-BASELINE.json, audit/baseline|vscode source). Generated-vs-source consistency is enforced by check-design-system-8.0.0.mjs',
  };
}

/**
 * Environment fingerprint (directive §3.1/§3.2/§3.4).
 *
 * A PASS is only reproducible on the toolchain + OS that produced it. Binding
 * only (execution_id, git_head, worktree) let evidence from a different
 * node/go/bun/OS be stitched into the same acceptance batch. This hashes the
 * real, queryable environment descriptors so a toolchain or OS change opens a
 * NEW identity and invalidates prior evidence (§3.3 "环境变化").
 *
 * Deterministic and cached: the descriptors cannot change within a process.
 */
let ENV_FP_CACHE = null;
function toolVersion(cmd, args) {
  try {
    return execFileSync(cmd, args, { encoding: 'utf8', timeout: 10000, stdio: ['ignore', 'pipe', 'pipe'] }).trim().split('\n')[0];
  } catch { return 'unavailable'; }
}
export function environmentFingerprint() {
  if (ENV_FP_CACHE) return ENV_FP_CACHE;
  const descriptors = {
    node: process.version,
    go: toolVersion('go', ['version']),
    bun: toolVersion('bun', ['--version']),
    platform: os.platform(),
    arch: os.arch(),
    release: os.release(),
  };
  ENV_FP_CACHE = hash(JSON.stringify(descriptors));
  return ENV_FP_CACHE;
}
export function environmentBasis() {
  return {
    algorithm: 'sha256(JSON({node,go,bun,platform,arch,release}))',
    note: 'toolchain + OS descriptors; a change invalidates prior evidence and opens a new execution identity',
  };
}

/** Resolve ledger paths, optionally injected for isolated tests. */
function ledgerPaths(stateDir) {
  const s = stateDir || STATE;
  return {
    current: path.join(s, 'current-execution.json'),
    history: path.join(s, 'executions.jsonl'),
    closures: path.join(s, 'execution-closures.jsonl'),
  };
}

function readClosures(closuresFile) {
  const map = new Map();
  if (!fs.existsSync(closuresFile)) return map;
  for (const line of fs.readFileSync(closuresFile, 'utf8').split('\n').filter(Boolean)) {
    try { const c = JSON.parse(line); if (c && c.execution_id) map.set(c.execution_id, c); } catch { /* skip malformed */ }
  }
  return map;
}

/**
 * Append-only execution ledger with EFFECTIVE status. A start entry keeps its
 * original RUNNING status in executions.jsonl (immutable); when a closure
 * exists the effective terminal status is overlaid. Never drops or reorders
 * entries, so identity-race / ordering assertions remain valid.
 */
export function executionHistory({ stateDir } = {}) {
  const { history, closures } = ledgerPaths(stateDir);
  if (!fs.existsSync(history)) return [];
  const closed = readClosures(closures);
  return fs.readFileSync(history, 'utf8').split('\n').filter(Boolean)
    .map((line) => { try { return JSON.parse(line); } catch { return null; } })
    .filter(Boolean)
    .map((e) => {
      const c = closed.get(e.execution_id);
      return c ? { ...e, status: c.final_status, closed_at: c.closed_at, closure_reason: c.reason } : e;
    });
}

/**
 * Record a terminal transition for an execution (append-only, idempotent).
 * An already-closed execution is never re-closed, so recovery can run repeatedly
 * without duplicating history. `stateDir` injection keeps tests hermetic.
 */
export function closeExecution(execution_id, final_status, reason = null, { stateDir } = {}) {
  if (!execution_id) throw new Error('closeExecution: execution_id required');
  if (!EXECUTION_TERMINAL_STATUSES.includes(final_status)) {
    throw new Error(`closeExecution: invalid terminal status ${final_status}`);
  }
  const { closures } = ledgerPaths(stateDir);
  const existing = readClosures(closures).get(execution_id);
  if (existing) return existing; // idempotent
  const closure = { execution_id, final_status, reason, closed_at: nowISO() };
  fs.mkdirSync(path.dirname(closures), { recursive: true });
  fs.appendFileSync(closures, `${JSON.stringify(closure)}\n`, 'utf8');
  return closure;
}

/** Close the CURRENT execution (e.g. after a successful acceptance batch). */
export function completeExecution(final_status = 'COMPLETED', reason = 'acceptance-batch-finished', { stateDir } = {}) {
  const { current } = ledgerPaths(stateDir);
  const cur = readJSON(current, null);
  if (!cur?.execution_id) return null;
  return closeExecution(cur.execution_id, final_status, reason, { stateDir });
}

/** Cancel the current execution (directive §十 执行取消机制). */
export function cancelExecution(reason = 'cancelled-by-operator', { stateDir } = {}) {
  return completeExecution('CANCELLED', reason, { stateDir });
}

/**
 * Interrupt recovery / fake-running-state cleanup (directive §十).
 *
 * Only ONE execution can be current. Every OTHER ledger entry still RUNNING
 * was interrupted (crash / timeout / cancel) or superseded by a newer code
 * version; leaving it RUNNING is a fake live state. Close each as SUPERSEDED
 * with an auditable reason. The current identity is NEVER closed, already-closed
 * entries are skipped (idempotent), and nothing is deleted. Recovery never
 * reuses old evidence: a closed execution can no longer be current, so its
 * evidence fails the binding check on any later acceptance.
 */
export function reconcileExecutions({ stateDir, reason = 'interrupt-recovery: not the current execution identity', preserveExecutionId = null } = {}) {
  const { current, history, closures } = ledgerPaths(stateDir);
  const cur = readJSON(current, null);
  // The caller may pin the identity it just opened so a concurrent writer that
  // moved CURRENT can never cause this process to close its own live identity.
  const preserveId = preserveExecutionId || cur?.execution_id || null;
  const closed = readClosures(closures);
  const out = [];
  if (!fs.existsSync(history)) return { closed: out, current_execution_id: cur?.execution_id ?? null };
  for (const line of fs.readFileSync(history, 'utf8').split('\n').filter(Boolean)) {
    let e; try { e = JSON.parse(line); } catch { continue; }
    if (!e?.execution_id) continue;
    if (preserveId && e.execution_id === preserveId) continue; // never close the live one
    if (closed.has(e.execution_id)) continue; // already terminal
    if (e.status !== 'RUNNING') continue;
    out.push(closeExecution(e.execution_id, 'SUPERSEDED', reason, { stateDir }));
    closed.set(e.execution_id, out[out.length - 1]);
  }
  return { closed: out, current_execution_id: cur?.execution_id ?? null };
}

function acquireIdentityLock() {
  fs.mkdirSync(STATE, { recursive: true });
  const deadline = Date.now() + LOCK_WAIT_MS;
  for (;;) {
    try {
      fs.mkdirSync(LOCK);
      return true;
    } catch (error) {
      if (error.code !== 'EEXIST') throw error;
      // A crashed process may leave a directory behind. Reclaim only locks
      // that are demonstrably stale; never remove a live holder's lock.
      try {
        const age = Date.now() - fs.statSync(LOCK).mtimeMs;
        if (age > LOCK_STALE_MS) {
          fs.rmdirSync(LOCK);
          continue;
        }
      } catch { /* lock released concurrently; retry immediately */ }
      if (Date.now() >= deadline) return false;
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 15);
    }
  }
}

function releaseIdentityLock() {
  try { fs.rmdirSync(LOCK); } catch { /* already released */ }
}

/**
 * `precomputed` carries the (head, fingerprint) pair resolved BEFORE the lock
 * was acquired. Recomputing worktreeFingerprint() inside the critical section
 * runs several `git` subprocesses and hashes every untracked business file;
 * with 20+ concurrent workers that serialised work exceeded the lock deadline
 * and made healthy workers fail with "execution identity lock timed out".
 * The identity is still the SAME real value — it is simply computed outside
 * the lock and reused, so the critical section is a pure JSON read/write.
 */
function writeExecution(reason, precomputed = null) {
  const head = precomputed ? precomputed.head : gitHead();
  if (!head) throw new Error('cannot establish execution identity: git rev-parse HEAD failed');
  const fingerprint = precomputed
    ? precomputed.fingerprint
    : worktreeFingerprint();
  const execution = {
    execution_id: newId('UAP-EXEC'),
    git_head: head,
    worktree_fingerprint: fingerprint,
    environment_fingerprint: environmentFingerprint(),
    started_at: nowISO(),
    started_by: reason,
    status: 'RUNNING',
  };
  fs.appendFileSync(HISTORY, `${JSON.stringify(execution)}\n`, 'utf8');
  writeJSON(CURRENT, execution);
  return execution;
}

/** Explicitly open a new verification run. */
export function startExecution(reason = 'manual') {
  const head = gitHead();
  const fingerprint = worktreeFingerprint();
  if (!acquireIdentityLock()) throw new Error('execution identity lock timed out');
  let execution;
  try {
    execution = writeExecution(reason, { head, fingerprint });
  } finally {
    releaseIdentityLock();
  }
  // A fresh identity is now current: close orphaned RUNNING executions outside
  // the lock so no fake live state survives (directive §十 interrupt recovery).
  reconcileExecutions({ reason: `superseded-by-new-execution: ${execution.execution_id}`, preserveExecutionId: execution.execution_id });
  return execution;
}

/**
 * Return the identity of the current verification run. If the code version
 * changed, a fresh identity is opened; the old one is retained in the ledger
 * so its evidence can never be promoted to a PASS for the new code.
 *
 * The slow path takes a cross-process lock and RE-READS the identity after
 * acquiring it: a concurrent worker may have already opened the identity we
 * need, in which case we adopt it instead of opening a duplicate.
 */
/**
 * Optional single-batch lock, set ONLY by the final-remediation orchestrator
 * for the duration of one acceptance batch.
 *
 * Problem it solves: several negative tests (WIP protection / real repair E2E)
 * append a marker to a TRACKED file and restore it in a finally block. The
 * repair engine calls currentExecution() inside that window, observes a
 * changed worktreeFingerprint and opens a NEW execution identity. The batch
 * then splits permanently even though the source ends up byte-identical, and
 * 15 final reports end up bound to different execution_ids.
 *
 * The lock does NOT weaken any check: it only pins WHICH identity is returned.
 * worktreeFingerprint() is still recomputed independently by the orchestrator
 * after every step and by verifyEvidenceManifest({strictCurrent:true}); a real
 * source change still fails closed. A mismatched lock is a hard error, never
 * a silent fallback.
 */
const BATCH_LOCK_ID = process.env.UAP_BATCH_LOCK_ID || null;

export function currentExecution() {
  if (BATCH_LOCK_ID) {
    const locked = readJSON(CURRENT, null);
    if (!locked || locked.execution_id !== BATCH_LOCK_ID) {
      throw new Error(`execution batch lock ${BATCH_LOCK_ID} does not match current identity (fail-closed)`);
    }
    if (locked.git_head !== gitHead()) {
      throw new Error(`execution batch lock ${BATCH_LOCK_ID} HEAD mismatch (fail-closed)`);
    }
    if (locked.environment_fingerprint !== environmentFingerprint()) {
      throw new Error(`execution batch lock ${BATCH_LOCK_ID} environment fingerprint mismatch (fail-closed)`);
    }
    return locked;
  }
  const head = gitHead();
  const fp = worktreeFingerprint();
  const envFp = environmentFingerprint();
  const cur = readJSON(CURRENT, null);
  if (cur && cur.execution_id && cur.git_head === head
      && cur.worktree_fingerprint === fp
      && cur.environment_fingerprint === envFp) return cur;
  if (!acquireIdentityLock()) throw new Error('execution identity lock timed out');
  let result;
  let openedNew = false;
  try {
    const latest = readJSON(CURRENT, null);
    if (latest && latest.execution_id && latest.git_head === head
        && latest.worktree_fingerprint === fp
        && latest.environment_fingerprint === envFp) {
      result = latest;
    } else {
      result = writeExecution(latest ? 'code-version-changed' : 'bootstrap', { head, fingerprint: fp });
      openedNew = true;
    }
  } finally {
    releaseIdentityLock();
  }
  // A new code version supersedes every prior RUNNING identity. Close the
  // orphans outside the lock so churn (e.g. WIP-protection probes) never leaves
  // fake live state behind (directive §十). preserveExecutionId guarantees this
  // process never closes the identity it just opened, even under concurrency.
  if (openedNew) {
    reconcileExecutions({ reason: `superseded-by-new-execution: ${result.execution_id}`, preserveExecutionId: result.execution_id });
  }
  return result;
}

/** Bind an artefact to the current execution. */
export function bindExecution(artefact = {}) {
  const e = currentExecution();
  // Identity always wins: an artefact may never declare its own binding.
  return {
    ...artefact,
    execution_id: e.execution_id,
    git_head: e.git_head,
    worktree_fingerprint: e.worktree_fingerprint,
    environment_fingerprint: e.environment_fingerprint,
  };
}

export function health() {
  try {
    const e = currentExecution();
    return {
      component, version, ok: Boolean(e.execution_id && e.git_head),
      checks: {
        git_head_resolved: Boolean(e.git_head),
        worktree_fingerprint_resolved: Boolean(e.worktree_fingerprint),
        ledger_present: fs.existsSync(HISTORY),
        identity_stable: currentExecution().execution_id === e.execution_id,
      },
      execution_id: e.execution_id, git_head: e.git_head,
      worktree_fingerprint: e.worktree_fingerprint,
      environment_fingerprint: e.environment_fingerprint, checked_at: nowISO(),
    };
  } catch (error) {
    return { component, version, ok: false, checks: {}, error: error.message, checked_at: nowISO() };
  }
}
