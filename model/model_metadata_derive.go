// The official catalog lags behind the model names channels actually serve: a
// vendor ships `deepseek-v4-flash-0731` or `doubao-seedream-5-0-260128` weeks
// before the catalog gains an entry. Those models would otherwise stay blank in
// the admin table forever, because the automatic fill can only copy what the
// catalog knows.
//
// DeriveMetadataValuesFromCatalog fills such a gap by inheritance rather than
// invention. It resolves a model name to the closest catalog relative and
// reuses that record's metadata, then re-labels the description so the operator
// can tell an inherited record from a catalog-authored one. Nothing is guessed
// that the catalog does not already assert about the same family: a name whose
// family is entirely unknown is left blank rather than filled with a guess.

// catalogRelativeSuffix matches the variant decorations vendors append to a
// base model name: dated snapshots (`-260128`, `-0731`), release qualifiers
// (`-thinking`, `-ga`, `-mini`, `-fast`), and the `preview`/`latest` markers.
var catalogRelativeSuffix = regexp.MustCompile(
	`(?i)^(?:` +
		`\d{4}-\d{2}-\d{2}` + // 2026-01-28
		`|\d{6,8}` + // 260128 / 0731
		`|v\d+(?:\.\d+)*` + // v2 / v2.1
		`|preview|latest|stable|thinking|reasoning|nonthinking` +
		`|ga|gb|rc|beta|alpha` +
		`|mini|max|pro|plus|flash|turbo|fast|light|lite|nano|standard|extreme` +
		`)$`)

// catalogRelativeStopWords are tokens that mark a name as a distinct product
// line rather than a variant of a shorter one. Stripping past one of these
// would cross a family boundary, so sibling resolution stops in front of it.
var catalogRelativeStopWords = map[string]bool{
	"image": true, "images": true, "video": true, "videos": true,
	"t2i": true, "i2v": true, "t2v": true, "audio": true, "speech": true,
	"embedding": true, "embed": true, "rerank": true, "search": true,
}

// DeriveMetadataValues resolves one model name against the official catalog.
//
// Resolution proceeds from most to least specific so the closest relative
// always wins:
//
//  1. An exact catalog entry.
//  2. The longest catalog name that is a dash-delimited prefix of the model
//     name (`deepseek-v4-flash-0731` → `deepseek-v4-flash`). This covers dated
//     snapshots and qualifier variants of a known model.
//  3. The same prefix walk with version segments relaxed onto a catalogued
//     sibling (`kimi-k2.5` → `kimi-k2.6`, `gpt-image-2.5-flare` → `gpt-image-2`).
//  4. The walk again after dropping trailing variant decorations
//     (`x-pro-0813` → `x`).
//
// When no relative exists at all — a product line the catalog has never
// heard of, such as an image or video model family that launched after the
// last catalog publish — resolution falls back to keyword attribution, which
// derives the vendor from the model name alone and describes the model's
// capability from its own product keyword. That fallback never invents
// descriptive prose: it labels the record as keyword-derived and leaves the
// description for an operator to finish.
//
// The returned values carry the relative's description re-labelled with the
// model's own name, its name rule and visibility, and the relative's icon,
// vendor, endpoints and tags. The boolean reports whether anything was derived.
func DeriveMetadataValuesFromCatalog(modelName string, catalog map[string]MetadataValues) (MetadataValues, bool) {
	modelName = strings.TrimSpace(modelName)
	if modelName == "" {
		return MetadataValues{}, false
	}
	if exact, ok := catalog[modelName]; ok {
		return exact, true
	}
	if relativeName, relative, ok := nearestCatalogRelative(modelName, catalog); ok {
		values := MetadataValues{
			Icon:      relative.Icon,
			Tags:      relative.Tags,
			Vendor:    relative.Vendor,
			Endpoints: relative.Endpoints,
			NameRule:  NameRuleExact,
			Status:    defaultDerivedStatus(relative.Status),
		}
		values.Description = inheritedDescription(modelName, relative.Description, relativeName)
		values.Tags = DerivedMetadataTags(modelName, values.Tags)
		return values, true
	}
	return DeriveMetadataValuesFromKeywords(modelName)
}

// nearestCatalogRelative finds the closest catalog entry for a model name.
//
// Candidates are generated by walking dash-delimited prefixes, longest first,
// and are then relaxed one step at a time so a name that differs from a
// catalogued model only in a version number or a trailing variant decoration
// still resolves. Relaxation is deliberately narrow: it can only ever produce
// a name that is segment-for-segment identical to the model except for version
// segments and known variant suffixes, and a prefix that would cross a
// product-line boundary is rejected.
func nearestCatalogRelative(modelName string, catalog map[string]MetadataValues) (string, MetadataValues, bool) {
	segments := strings.Split(modelName, "-")
	names := sortedCatalogNames(catalog)

	// Pass 1: plain prefix walk, longest first.
	for end := len(segments) - 1; end >= 1; end-- {
		if values, ok := catalog[strings.Join(segments[:end], "-")]; ok {
			if prefixCrossesProductLine(segments, end) {
				continue
			}
			return strings.Join(segments[:end], "-"), values, true
		}
	}

	// Pass 2: a dotted version may differ from a catalogued sibling's, so retry
	// each prefix with its version segments relaxed onto the sibling that shares
	// every other segment (`kimi-k2.5` → `kimi-k2.6`, `gpt-image-2.5-flare` →
	// `gpt-image-2`).
	//
	// The full name is included: it was skipped by the plain lookup above only
	// because no entry matches it verbatim, not because it is ineligible as a
	// version sibling of a catalogued name.
	for end := len(segments); end >= 1; end-- {
		prefix := segments[:end]
		if prefixCrossesProductLine(segments, end) {
			continue
		}
		if name, values, ok := relaxedVersionMatch(prefix, names, catalog); ok {
			return name, values, true
		}
	}

	// Pass 3: drop trailing variant decorations, then walk again, so
	// `x-pro-0813` can still reach `x`.
	trimmed := trimVariantTail(segments)
	for end := len(trimmed) - 1; end >= 1; end-- {
		candidate := strings.Join(trimmed[:end], "-")
		if candidate == modelName {
			continue
		}
		if values, ok := catalog[candidate]; ok {
			if prefixCrossesProductLine(trimmed, end) {
				continue
			}
			return candidate, values, true
		}
	}
	return "", MetadataValues{}, false
}

// prefixCrossesProductLine reports whether cutting the name after `end`
// segments would drop a product-line word (`image`, `video`, …) into the tail.
// Such a cut separates two different kinds of model, so it is never a valid
// relative.
func prefixCrossesProductLine(segments []string, end int) bool {
	if end >= len(segments) {
		return false
	}
	return catalogRelativeStopWords[strings.ToLower(segments[end])]
}

// versionSegmentPattern matches a segment that is a version number, dotted or
// not, optionally carrying a short letter prefix: `k2.5`, `v2.1`, `2`, `1.0`,
// `4`. Versions are what make two names the same product line at different
// releases, so they are the only segments allowed to differ from a relative.
//
// A bare integer counts, which is what lets `gpt-image-2.5` recognise the
// catalogued `gpt-image-2` and `deepseek-v4-1-flash` sit beside `deepseek-v4`.
// A leading letter is only allowed when a dotted version follows it, so `ab`
// (a family name) and `360` (a vendor) are not mistaken for versions: `k2.5`
// qualifies, `k2` does not.
var versionSegmentPattern = regexp.MustCompile(`^(?:[A-Za-z][0-9]+(?:\.[0-9]+)+|[0-9]+(?:\.[0-9]+)*)$`)

// relaxedVersionMatch finds a catalog name that equals `prefix` except that one
// or more dotted-version segments carry a different version. Every other
// segment must match exactly, so the result is always another version of the
// same product line. The relative whose version is numerically closest wins, so
// `gpt-image-2.5` prefers a catalogued `gpt-image-2` over `gpt-image-1.5`
// instead of picking whichever name happens to be longer.
func relaxedVersionMatch(prefix []string, names []string, catalog map[string]MetadataValues) (string, MetadataValues, bool) {
	versionIndexes := make([]int, 0, len(prefix))
	for i, segment := range prefix {
		if versionSegmentPattern.MatchString(segment) {
			versionIndexes = append(versionIndexes, i)
		}
	}
	if len(versionIndexes) == 0 {
		return "", MetadataValues{}, false
	}
	want := strings.Join(prefix, "-")
	bestName := ""
	bestDistance := 0.0
	for _, name := range names {
		other := strings.Split(name, "-")
		if len(other) != len(prefix) {
			continue
		}
		isVersion := false
		matches := true
		distance := 0.0
		for i := range prefix {
			if other[i] == prefix[i] {
				continue
			}
			if !versionSegmentPattern.MatchString(other[i]) {
				matches = false
				break
			}
			isVersion = true
			distance += versionSegmentDistance(prefix[i], other[i])
		}
		if !matches || !isVersion || name == want {
			continue
		}
		// The lowest version distance wins; alphabetical order breaks ties so
		// the result never depends on map iteration order.
		if bestName == "" || distance < bestDistance ||
			(distance == bestDistance && name < bestName) {
			bestName, bestDistance = name, distance
		}
	}
	if bestName == "" {
		return "", MetadataValues{}, false
	}
	return bestName, catalog[bestName], true
}

// versionSegmentDistance scores how far apart two version segments are, so a
// neighbouring release is preferred over a distant one. A segment with no
// digits cannot be compared and scores as unrelated.
func versionSegmentDistance(a, b string) float64 {
	aNumbers := versionSegmentNumbers(a)
	bNumbers := versionSegmentNumbers(b)
	if len(aNumbers) == 0 || len(bNumbers) == 0 {
		return incomparableVersionDistance
	}
	distance := 0.0
	for i := 0; i < len(aNumbers) || i < len(bNumbers); i++ {
		var left, right float64
		if i < len(aNumbers) {
			left = aNumbers[i]
		}
		if i < len(bNumbers) {
			right = bNumbers[i]
		}
		distance += absFloat(left - right)
	}
	return distance
}

// incomparableVersionDistance keeps an opaque build tag from ever being
// preferred over a comparable numeric release.
const incomparableVersionDistance = 1e6

// versionSegmentNumbers extracts the numeric components of a version segment.
//
// A dotted version is one number, not several: `2.5` is the release 2.5 and
// must compare as a single value, otherwise it would score as the two numbers 2
// and 5 and end up "further" from `2` than `1.5` is. The dotted form is
// therefore taken first; a segment with no dot yields its digits as one number.
func versionSegmentNumbers(segment string) []float64 {
	trimmed := strings.TrimLeft(segment, "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ")
	if trimmed == "" {
		return nil
	}
	value, err := strconv.ParseFloat(trimmed, 64)
	if err != nil {
		return nil
	}
	return []float64{value}
}

func absFloat(value float64) float64 {
	if value < 0 {
		return -value
	}
	return value
}

// sortedCatalogNames returns the catalog keys ordered longest-first then
// alphabetically, so every relaxation picks the closest relative and the result
// does not depend on map iteration order.
func sortedCatalogNames(catalog map[string]MetadataValues) []string {
	names := make([]string, 0, len(catalog))
	for name := range catalog {
		names = append(names, name)
	}
	sort.Slice(names, func(i, j int) bool {
		if len(names[i]) != len(names[j]) {
			return len(names[i]) > len(names[j])
		}
		return names[i] < names[j]
	})
	return names
}

// trimVariantTail removes trailing tokens that are known variant decorations
// rather than part of a product name.
func trimVariantTail(segments []string) []string {
	result := segments
	for len(result) > 1 {
		last := strings.ToLower(result[len(result)-1])
		if catalogRelativeSuffix.MatchString(last) {
			result = result[:len(result)-1]
			continue
		}
		break
	}
	return result
}

// inheritedDescription re-labels an inherited description with the model's own
// name so an operator reviewing the admin table can see that the text was
// carried over from a sibling rather than authored for this model. The
// relative's name is always mentioned, so the provenance is unambiguous.
func inheritedDescription(modelName, relativeDescription, relativeName string) string {
	name := strings.TrimSpace(modelName)
	base := strings.TrimSpace(relativeDescription)
	if base == "" {
		return name + " — metadata inherited from " + relativeName
	}
	return name + " — inherited from " + relativeName + ": " + base
}

// keywordDescription states what the name itself asserts, with no invented
// detail. It is deliberately short so a reviewer can tell at a glance that the
// record was attributed by keyword rather than copied from the catalog.
func keywordDescription(modelName, capability string) string {
	if capability == "" {
		return modelName + " — attributed by model name; official description pending"
	}
	return modelName + " — " + capability + " model attributed by model name; official description pending"
}

// DeriveMetadataValuesFromKeywords attributes a model that the official catalog
// has never heard of.
//
// A new product line reaches the relay before the catalog publishes it, and
// leaving those rows blank is what makes the admin table report missing
// metadata. The vendor comes from the same name rules the pricing plaza already
// uses to attribute uncatalogued models, so both views agree on who provides a
// model. The capability and tags come from the model's own product keyword, and
// the description says plainly that it was attributed by name.
//
// Nothing is invented: a name that matches no brand rule yields nothing, so a
// model is never filed under a vendor the name does not imply.
func DeriveMetadataValuesFromKeywords(modelName string) (MetadataValues, bool) {
	modelName = strings.TrimSpace(modelName)
	if modelName == "" {
		return MetadataValues{}, false
	}
	vendorName := keywordVendorForModel(modelName)
	if vendorName == "" {
		return MetadataValues{}, false
	}
	capability := modelCapabilityFromName(modelName)
	return MetadataValues{
		Description: keywordDescription(modelName, capability),
		Icon:        getDefaultVendorIcon(vendorName),
		Tags:        DerivedMetadataTags(modelName, ""),
		Vendor:      vendorName,
		NameRule:    NameRuleExact,
		Status:      1,
	}, true
}

// keywordVendorForModel resolves the brand a model name is filed under, but
// only when the brand token it matched is the model's own leading token.
//
// defaultVendorNameForModel matches anywhere in the name, which is right for
// the pricing plaza: a channel may prefix a vendor's models with its own
// routing prefix. For a metadata row, though, a contained match would file a
// distinct product line under the wrong brand — `qwen-image-2.5` contains
// `qwen` but is an image model, not a member of the Qwen text family, and the
// catalog usually lists those two lines separately. Requiring the brand to
// open the name keeps a keyword-derived record on the line its name declares.
//
// A model whose brand is not its first token falls back to the plaza's own
// attribution, so an operator still sees a vendor rather than a blank row; the
// distinction only matters where the catalog genuinely separates the lines.
func keywordVendorForModel(modelName string) string {
	segments := strings.Split(strings.ToLower(modelName), "-")
	head := segments[0]
	if head == "" {
		return ""
	}
	// A brand token immediately followed by a product-line word names a
	// different line than the brand's own models: `qwen-image-*` is an image
	// model, not a Qwen text model. The catalog lists those separately, so
	// keyword attribution must not merge them.
	if len(segments) > 1 && catalogRelativeStopWords[segments[1]] {
		return ""
	}
	for _, pattern := range defaultVendorPatterns {
		if head == pattern {
			return defaultVendorRules[pattern]
		}
	}
	return defaultVendorNameForModel(modelName)
}

// modelCapabilityFromName reports the product capability a model name asserts,
// used only to label a keyword-derived record. An unrecognised name yields an
// empty string rather than a guess.
func modelCapabilityFromName(modelName string) string {
	lower := strings.ToLower(modelName)
	if common.IsImageGenerationModel(lower) {
		return "image generation"
	}
	if isVideoModelName(lower) {
		return "video generation"
	}
	if strings.Contains(lower, "embedding") {
		return "text embedding"
	}
	return ""
}

// defaultDerivedStatus keeps a derived record visible only when the relative it
// came from is itself visible; a deprecated relative must not promote an
// unseen model into the catalog.
func defaultDerivedStatus(relativeStatus int) int {
	if relativeStatus == 0 {
		return 0
	}
	return 1
}

// DerivedMetadataTags appends the capability tags implied by a model name when
// the relative did not carry them, so an image or video model is still
// classified correctly in the pricing filters.
//
// The tag vocabulary matches the official catalog: Files and Vision for image
// generation, Vision for video. It only ever adds tags, never removes them.
func DerivedMetadataTags(modelName, tags string) string {
	existing := map[string]bool{}
	for _, tag := range strings.Split(tags, ",") {
		if trimmed := strings.TrimSpace(tag); trimmed != "" {
			existing[trimmed] = true
		}
	}
	var additions []string
	appendTag := func(value string) {
		if !existing[value] {
			existing[value] = true
			additions = append(additions, value)
		}
	}
	lower := strings.ToLower(modelName)
	if common.IsImageGenerationModel(lower) {
		appendTag("Files")
		appendTag("Vision")
	}
	if isVideoModelName(lower) {
		appendTag("Vision")
	}
	if len(additions) == 0 {
		return tags
	}
	if strings.TrimSpace(tags) == "" {
		return strings.Join(additions, ",")
	}
	return tags + "," + strings.Join(additions, ",")
}

// videoModelKeywords are the name fragments that identify a video generation
// model. The relay does not expose a shared classifier for video, so the list
// is kept here next to the tags it produces.
var videoModelKeywords = []string{
	"seedance", "vidu", "kling", "jimeng", "sora", "veo", "wan2.",
	"i2v", "t2v", "video",
}

func isVideoModelName(lowerName string) bool {
	for _, keyword := range videoModelKeywords {
		if strings.Contains(lowerName, keyword) {
			return true
		}
	}
	return false
}
